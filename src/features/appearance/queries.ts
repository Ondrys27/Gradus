"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useSession } from "@/features/account/queries";
import { createClient } from "@/lib/supabase/client";
import { parseCustomThemeTokens, type CustomThemeTokens } from "./custom-tokens";

/** One of the user's custom themes, as the app uses it (tokens already checked). */
export type CustomTheme = {
  id: string;
  name: string;
  tokens: CustomThemeTokens;
  shareCode: string;
  createdAt: string;
  updatedAt: string;
};

export const appearanceKeys = {
  customThemes: (userId: string) => ["appearance", userId, "custom-themes"] as const,
  allowed: (userId: string) => ["appearance", userId, "custom-themes-allowed"] as const,
  shared: (userId: string, code: string) => ["appearance", userId, "shared", code] as const,
};

const COLUMNS = "id, name, tokens, share_code, created_at, updated_at" as const;

type Row = {
  id: string;
  name: string;
  tokens: unknown;
  share_code: string;
  created_at: string;
  updated_at: string;
};

function toTheme(row: Row): CustomTheme | null {
  const tokens = parseCustomThemeTokens(row.tokens);
  if (!tokens) return null;
  return {
    id: row.id,
    name: row.name,
    tokens,
    shareCode: row.share_code,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}

/** The user's custom themes (at most 12, own rows only), oldest first. */
export function useCustomThemes() {
  const { user } = useSession();
  return useQuery({
    queryKey: appearanceKeys.customThemes(user.id),
    queryFn: async () => {
      const { data, error } = await createClient()
        .from("custom_themes")
        .select(COLUMNS)
        .eq("user_id", user.id)
        .order("created_at")
        .limit(12);
      if (error) throw error;
      return (data ?? []).map(toTheme).filter((theme): theme is CustomTheme => theme !== null);
    },
    staleTime: 5 * 60_000,
  });
}

/** Whether the account's plan lets it make custom themes (catalog flag, missing = yes). */
export function useCustomThemesAllowed() {
  const { user } = useSession();
  return useQuery({
    queryKey: appearanceKeys.allowed(user.id),
    queryFn: async () => {
      const { data, error } = await createClient().rpc("custom_themes_allowed");
      if (error) throw error;
      return data === true;
    },
    staleTime: 10 * 60_000,
  });
}

/** A colleague's theme by its share code; null when it does not exist or is not theirs to give. */
export function useSharedTheme(code: string | null) {
  const { user } = useSession();
  return useQuery({
    queryKey: appearanceKeys.shared(user.id, code ?? ""),
    enabled: code !== null,
    queryFn: async () => {
      const { data, error } = await createClient().rpc("custom_theme_by_code", {
        _code: code ?? "",
      });
      if (error) throw error;
      const row = data?.[0];
      const tokens = row ? parseCustomThemeTokens(row.tokens) : null;
      return row && tokens ? { name: row.name, author: row.author, tokens } : null;
    },
    staleTime: 60_000,
    retry: false,
  });
}

export type SaveCustomTheme = { id?: string; name: string; tokens: CustomThemeTokens };

/** Creates (no id) or updates a custom theme; the database checks shape, contrast, limit and plan. */
export function useSaveCustomTheme() {
  const { user } = useSession();
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async ({ id, name, tokens }: SaveCustomTheme) => {
      const db = createClient();
      const query = id
        ? db.from("custom_themes").update({ name, tokens }).eq("id", id).eq("user_id", user.id)
        : // share_code is NOT NULL but always generated by custom_themes_guard; the placeholder is overwritten.
          db.from("custom_themes").insert({ name, tokens, share_code: "" });
      const { data, error } = await query.select(COLUMNS).single();
      if (error) throw error;
      const theme = toTheme(data);
      if (!theme) throw new Error("custom_theme_invalid");
      return theme;
    },
    onSuccess: (theme) => {
      queryClient.setQueryData<CustomTheme[]>(appearanceKeys.customThemes(user.id), (list) => {
        const rest = (list ?? []).filter((item) => item.id !== theme.id);
        return [...rest, theme].sort((a, b) => a.createdAt.localeCompare(b.createdAt));
      });
    },
  });
}

export function useDeleteCustomTheme() {
  const { user } = useSession();
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (id: string) => {
      const { error } = await createClient()
        .from("custom_themes")
        .delete()
        .eq("id", id)
        .eq("user_id", user.id);
      if (error) throw error;
      return id;
    },
    onSuccess: (id) => {
      queryClient.setQueryData<CustomTheme[]>(appearanceKeys.customThemes(user.id), (list) =>
        (list ?? []).filter((item) => item.id !== id),
      );
    },
  });
}

/** The database's refusal as a short code for the message (limit, plan, contrast). */
export function saveErrorCode(error: unknown): "limit" | "plan" | "unreadable" | "generic" {
  const message =
    error instanceof Error ? error.message : String((error as { message?: string })?.message ?? "");
  if (message.includes("custom_theme_limit")) return "limit";
  if (message.includes("custom_themes_plan")) return "plan";
  if (message.includes("custom_themes_readable") || message.includes("custom_themes_tokens"))
    return "unreadable";
  return "generic";
}
